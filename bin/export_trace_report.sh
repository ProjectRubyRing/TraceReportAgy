#!/usr/bin/env bash
# ==============================================================================
# Script: export_trace_report.sh
# Purpose: Query CloudWatch Logs Insights on 'aws/spans' (Transaction Search),
#          export results to CSV, and inject into an Excel report matching
#          the AWS X-Ray Trace Details console view.
# Target OS: RHEL 9.8 (Red Hat Enterprise Linux 9.8) / Bash 5.1+
# ==============================================================================

set -euo pipefail

# Script directory resolution
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN_NAME="$(basename "${BASH_SOURCE[0]}")"

# Color codes (disabled if not terminal or NO_COLOR is set)
if [[ -t 1 ]] && [[ -z "${NO_COLOR:-}" ]]; then
    COLOR_RESET="\033[0m"
    COLOR_BOLD="\033[1m"
    COLOR_GREEN="\033[32m"
    COLOR_YELLOW="\033[33m"
    COLOR_RED="\033[31m"
    COLOR_CYAN="\033[36m"
    COLOR_BLUE="\033[34m"
else
    COLOR_RESET=""
    COLOR_BOLD=""
    COLOR_GREEN=""
    COLOR_YELLOW=""
    COLOR_RED=""
    COLOR_CYAN=""
    COLOR_BLUE=""
fi

# Log helper functions
log_info()    { echo -e "${COLOR_CYAN}[INFO]${COLOR_RESET} $*"; }
log_success() { echo -e "${COLOR_GREEN}[SUCCESS]${COLOR_RESET} $*"; }
log_warn()    { echo -e "${COLOR_YELLOW}[WARN]${COLOR_RESET} $*" >&2; }
log_error()   { echo -e "${COLOR_RED}[ERROR]${COLOR_RESET} $*" >&2; }

# Default values
DEFAULT_LOG_GROUP="aws/spans"
DEFAULT_START_TIME="1h"
DEFAULT_END_TIME="now"
DEFAULT_OUTPUT_DIR="${SCRIPT_DIR}/output"
DEFAULT_TEMPLATE_PATH="${SCRIPT_DIR}/templates/trace_report_template.xlsx"
DEFAULT_LIMIT=10000

LOG_GROUP="${DEFAULT_LOG_GROUP}"
START_TIME_INPUT="${DEFAULT_START_TIME}"
END_TIME_INPUT="${DEFAULT_END_TIME}"
OUTPUT_DIR="${DEFAULT_OUTPUT_DIR}"
TEMPLATE_PATH="${DEFAULT_TEMPLATE_PATH}"
LIMIT="${DEFAULT_LIMIT}"
TRACE_ID=""
FILTER_CONDITION=""
CUSTOM_QUERY=""
AWS_PROFILE=""
AWS_REGION=""
DRY_RUN=0
MOCK_MODE=0

# Usage documentation
show_help() {
    cat << EOF
${COLOR_BOLD}Usage:${COLOR_RESET}
  ${BIN_NAME} [options]

${COLOR_BOLD}Description:${COLOR_RESET}
  Executes a time-ranged CloudWatch Logs Insights query against the
  span-dedicated log group ('aws/spans') generated by AWS Transaction Search /
  Application Signals, exports the result to CSV, and injects the spans into
  an AWS X-Ray style Excel report workbook (.xlsx).

${COLOR_BOLD}Options:${COLOR_RESET}
  -s, --start-time <TIME>   Query start time. Accepts:
                            - ISO 8601: "2026-10-26T04:00:00Z", "2026-10-26 04:00:00"
                            - Relative: "1h", "30m", "24h", "2d", "1 hour ago"
                            - Unix Epoch: 1792982400
                            (Default: "${DEFAULT_START_TIME}" [1 hour ago])

  -e, --end-time <TIME>     Query end time. Same formats as --start-time.
                            (Default: "${DEFAULT_END_TIME}" [current time])

  -g, --log-group <NAME>    Target CloudWatch log group.
                            (Default: "${DEFAULT_LOG_GROUP}")

  -t, --trace-id <ID>       Filter by specific Trace ID (e.g. 1-671c6d1f-81812839...)
                            When specified, generates focused waterfall report for this trace.

  -f, --filter <CONDITION>  Extra CloudWatch Logs Insights filter expression.
                            (e.g. "attributes.aws.local.service = 'order-service'")

  -q, --query <QUERY_STR>   Full custom CloudWatch Logs Insights query string.
                            Overrides default fields and filters.

  -o, --output-dir <DIR>    Directory to save exported CSV and Excel report.
                            (Default: "${DEFAULT_OUTPUT_DIR}")

  -p, --profile <NAME>      AWS CLI profile name to use.

  -r, --region <REGION>     AWS region (e.g. ap-northeast-1, us-east-1).

      --template <PATH>     Path to custom Excel template.
                            (Default: "${DEFAULT_TEMPLATE_PATH}")

      --limit <NUM>         Maximum log records to return (Default: ${DEFAULT_LIMIT}).

      --mock                Run in mock mode using bundled sample trace spans
                            (useful for offline testing without live AWS credentials).

      --dry-run             Show parsed query, parameters and commands without running.

  -h, --help                Display this help message.

${COLOR_BOLD}Examples:${COLOR_RESET}
  # 1. Query past 1 hour spans on 'aws/spans' and generate Excel report
  ${BIN_NAME} --start-time 1h

  # 2. Query specific time range in JST / UTC
  ${BIN_NAME} --start-time "2026-10-26 00:00:00" --end-time "2026-10-26 01:00:00"

  # 3. Query specific Trace ID
  ${BIN_NAME} --trace-id "1-671c6d1f-8181283921839182391283" --start-time 24h

  # 4. Filter by service name with custom AWS profile and region
  ${BIN_NAME} -s 2h -f "attributes.aws.local.service = 'order-frontend'" -p prod -r ap-northeast-1

  # 5. Offline test using mock data
  ${BIN_NAME} --mock
EOF
}

# Parse command line options
parse_arguments() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            -s|--start-time)
                START_TIME_INPUT="$2"; shift 2 ;;
            -e|--end-time)
                END_TIME_INPUT="$2"; shift 2 ;;
            -g|--log-group)
                LOG_GROUP="$2"; shift 2 ;;
            -t|--trace-id)
                TRACE_ID="$2"; shift 2 ;;
            -f|--filter)
                FILTER_CONDITION="$2"; shift 2 ;;
            -q|--query)
                CUSTOM_QUERY="$2"; shift 2 ;;
            -o|--output-dir)
                OUTPUT_DIR="$2"; shift 2 ;;
            -p|--profile)
                AWS_PROFILE="$2"; shift 2 ;;
            -r|--region)
                AWS_REGION="$2"; shift 2 ;;
            --template)
                TEMPLATE_PATH="$2"; shift 2 ;;
            --limit)
                LIMIT="$2"; shift 2 ;;
            --mock)
                MOCK_MODE=1; shift ;;
            --dry-run)
                DRY_RUN=1; shift ;;
            -h|--help)
                show_help; exit 0 ;;
            *)
                log_error "Unknown option: $1"
                show_help
                exit 1 ;;
        esac
    done
}

# Convert various date inputs (ISO, relative, epoch) into Unix epoch seconds
to_epoch_seconds() {
    local input="$1"
    local now_epoch
    now_epoch="$(date +%s)"

    # If already pure digits (10-13 digits)
    if [[ "$input" =~ ^[0-9]{10}$ ]]; then
        echo "$input"
        return 0
    elif [[ "$input" =~ ^[0-9]{13}$ ]]; then
        # Milliseconds to seconds
        echo $(( input / 1000 ))
        return 0
    fi

    # Handle "now"
    if [[ "$input" == "now" ]]; then
        echo "$now_epoch"
        return 0
    fi

    # Handle shorthand relative syntax: e.g. "30m", "1h", "24h", "2d"
    if [[ "$input" =~ ^([0-9]+)[[:space:]]*([smhd])$ ]]; then
        local num="${BASH_REMATCH[1]}"
        local unit="${BASH_REMATCH[2]}"
        case "$unit" in
            s) echo $(( now_epoch - num )) ;;
            m) echo $(( now_epoch - (num * 60) )) ;;
            h) echo $(( now_epoch - (num * 3600) )) ;;
            d) echo $(( now_epoch - (num * 86400) )) ;;
        esac
        return 0
    fi

    # Use GNU date -d
    local parsed_epoch
    if parsed_epoch="$(date -d "$input" +%s 2>/dev/null)"; then
        echo "$parsed_epoch"
        return 0
    fi

    # Fallback using Python if GNU date fails on complex formats
    if parsed_epoch="$("$PYTHON_EXEC" -c "
import sys
from datetime import datetime
s = sys.argv[1].replace('T', ' ').replace('Z', '')
for fmt in ('%Y-%m-%d %H:%M:%S', '%Y-%m-%d %H:%M', '%Y-%m-%d'):
    try:
        print(int(datetime.strptime(s, fmt).timestamp()))
        sys.exit(0)
    except ValueError:
        pass
sys.exit(1)
" "$input" 2>/dev/null)"; then
        echo "$parsed_epoch"
        return 0
    fi

    log_error "Unable to parse date: '$input'. Supported formats: '1h', '30m', '2026-10-26T00:00:00Z', '2026-10-26 00:00:00'."
    exit 1
}

# Convert POSIX path to Windows path if using Windows python.exe in WSL / Git Bash
resolve_py_path() {
    local p="$1"
    if [[ "$PYTHON_EXEC" == *.exe ]] && command -v wslpath >/dev/null 2>&1; then
        wslpath -w "$p"
    elif [[ "$PYTHON_EXEC" == *.exe ]] && command -v cygpath >/dev/null 2>&1; then
        cygpath -w "$p"
    else
        echo "$p"
    fi
}

# Verify Python and openpyxl dependencies
check_python_environment() {
    PYTHON_EXEC=""

    # 0. Check user-supplied PYTHON_BIN environment variable
    if [[ -n "${PYTHON_BIN:-}" ]]; then
        if "$PYTHON_BIN" -c "import openpyxl" 2>/dev/null; then
            PYTHON_EXEC="$PYTHON_BIN"
        fi
    fi

    # 1. Check local virtualenv in project
    if [[ -z "$PYTHON_EXEC" && -x "${SCRIPT_DIR}/.venv/bin/python3" ]]; then
        if "${SCRIPT_DIR}/.venv/bin/python3" -c "import openpyxl" 2>/dev/null; then
            PYTHON_EXEC="${SCRIPT_DIR}/.venv/bin/python3"
        fi
    fi

    # 2. Check system python3
    if [[ -z "$PYTHON_EXEC" ]] && command -v python3 >/dev/null 2>&1; then
        if python3 -c "import openpyxl" 2>/dev/null; then
            PYTHON_EXEC="python3"
        fi
    fi

    # 3. Check 'python' on path
    if [[ -z "$PYTHON_EXEC" ]] && command -v python >/dev/null 2>&1; then
        if python -c "import openpyxl" 2>/dev/null; then
            PYTHON_EXEC="python"
        fi
    fi

    # 4. Check 'python.exe' on path (WSL / Git Bash interoperability)
    if [[ -z "$PYTHON_EXEC" ]] && command -v python.exe >/dev/null 2>&1; then
        if python.exe -c "import openpyxl" 2>/dev/null; then
            PYTHON_EXEC="python.exe"
        fi
    fi

    if [[ -z "$PYTHON_EXEC" ]]; then
        log_warn "Python 3 with 'openpyxl' module was not found."
        log_info "Attempting to create a local virtualenv (.venv) with openpyxl..."

        if command -v python3 >/dev/null 2>&1; then
            if python3 -m venv "${SCRIPT_DIR}/.venv" 2>/dev/null; then
                "${SCRIPT_DIR}/.venv/bin/pip" install --quiet openpyxl 2>/dev/null || true
                if "${SCRIPT_DIR}/.venv/bin/python3" -c "import openpyxl" 2>/dev/null; then
                    PYTHON_EXEC="${SCRIPT_DIR}/.venv/bin/python3"
                    log_success "Created local virtualenv with openpyxl: ${PYTHON_EXEC}"
                fi
            fi
        fi

        if [[ -z "$PYTHON_EXEC" ]]; then
            log_error "Failed to locate Python 3 with 'openpyxl'."
            log_error "On RHEL 9.8, please run:"
            log_error "  sudo dnf install -y python3 python3-openpyxl"
            log_error "or:"
            log_error "  pip install openpyxl"
            exit 1
        fi
    fi
}

# Check AWS CLI prerequisites
check_aws_cli() {
    if [[ "$MOCK_MODE" -eq 1 || "$DRY_RUN" -eq 1 ]]; then
        return 0
    fi

    AWS_EXEC=""
    if [[ -n "${AWS_CLI_BIN:-}" ]] && command -v "$AWS_CLI_BIN" >/dev/null 2>&1; then
        AWS_EXEC="$AWS_CLI_BIN"
    elif command -v aws >/dev/null 2>&1; then
        AWS_EXEC="aws"
    elif command -v aws.exe >/dev/null 2>&1; then
        AWS_EXEC="aws.exe"
    fi

    if [[ -z "$AWS_EXEC" ]]; then
        log_error "'aws' CLI is not installed or not in PATH."
        log_error "On RHEL 9.8, please install AWS CLI v2:"
        log_error "  curl 'https://awscli.amazonaws.com/awscli-exe-linux-x86_64.zip' -o 'awscliv2.zip'"
        log_error "  unzip awscliv2.zip && sudo ./aws/install"
        exit 1
    fi
}

# Build CloudWatch Logs Insights query string
build_query_string() {
    if [[ -n "$CUSTOM_QUERY" ]]; then
        echo "$CUSTOM_QUERY"
        return 0
    fi

    local query="fields @timestamp, traceId, spanId, parentSpanId, name, durationNano, coalesce(attributes.aws.local.service, \`resource.attributes.service.name\`, \`service.name\`, 'UnknownService') as service_name, coalesce(attributes.aws.local.operation, name) as operation_name, coalesce(attributes.http.response.status_code, \`http.status_code\`, '') as http_status, coalesce(attributes.http.method, \`http.method\`, '') as http_method, coalesce(attributes.http.target, \`http.target\`, attributes.url.full, '') as http_url, coalesce(status.code, '') as status_code, coalesce(status.message, '') as status_message, coalesce(kind, '') as kind"

    if [[ -n "$TRACE_ID" ]]; then
        query="${query} | filter traceId = '${TRACE_ID}' or trace_id = '${TRACE_ID}'"
    fi

    if [[ -n "$FILTER_CONDITION" ]]; then
        query="${query} | filter ${FILTER_CONDITION}"
    fi

    query="${query} | sort @timestamp asc | limit ${LIMIT}"
    echo "$query"
}

# Main Execution Flow
main() {
    parse_arguments "$@"

    echo -e "${COLOR_BOLD}============================================================${COLOR_RESET}"
    echo -e "${COLOR_BOLD} AWS CloudWatch Transaction Search - Trace Report Generator ${COLOR_RESET}"
    echo -e "${COLOR_BOLD} Target: RHEL 9.8 | Log Group: ${LOG_GROUP}${COLOR_RESET}"
    echo -e "${COLOR_BOLD}============================================================${COLOR_RESET}"

    # Verify runtime dependencies
    check_python_environment
    check_aws_cli

    # Parse and validate start/end time
    START_EPOCH="$(to_epoch_seconds "$START_TIME_INPUT")"
    END_EPOCH="$(to_epoch_seconds "$END_TIME_INPUT")"

    if [[ "$START_EPOCH" -ge "$END_EPOCH" ]]; then
        log_error "Start time ($(date -d @"$START_EPOCH" '+%Y-%m-%d %H:%M:%S UTC')) must be before end time ($(date -d @"$END_EPOCH" '+%Y-%m-%d %H:%M:%S UTC'))."
        exit 1
    fi

    START_ISO="$(date -u -d @"$START_EPOCH" '+%Y-%m-%d %H:%M:%S UTC')"
    END_ISO="$(date -u -d @"$END_EPOCH" '+%Y-%m-%d %H:%M:%S UTC')"
    TIMESTAMP_LABEL="$(date -u +%Y%m%d_%H%M%S)"

    mkdir -p "$OUTPUT_DIR"
    JSON_OUT_PATH="${OUTPUT_DIR}/query_results_${TIMESTAMP_LABEL}.json"
    CSV_OUT_PATH="${OUTPUT_DIR}/trace_spans_${TIMESTAMP_LABEL}.csv"
    EXCEL_OUT_PATH="${OUTPUT_DIR}/trace_report_${TIMESTAMP_LABEL}.xlsx"

    QUERY_STRING="$(build_query_string)"

    log_info "Log Group:    ${LOG_GROUP}"
    log_info "Start Time:   ${START_ISO} (${START_EPOCH})"
    log_info "End Time:     ${END_ISO} (${END_EPOCH})"
    log_info "Output Dir:   ${OUTPUT_DIR}"
    if [[ -n "$TRACE_ID" ]]; then
        log_info "Trace ID:     ${TRACE_ID}"
    fi
    if [[ -n "$FILTER_CONDITION" ]]; then
        log_info "Filter:       ${FILTER_CONDITION}"
    fi

    # Dry-run handling
    if [[ "$DRY_RUN" -eq 1 ]]; then
        echo ""
        log_info "${COLOR_BOLD}[DRY-RUN] Constructed Query:${COLOR_RESET}"
        echo -e "${COLOR_CYAN}${QUERY_STRING}${COLOR_RESET}"
        echo ""
        log_info "${COLOR_BOLD}[DRY-RUN] AWS CLI Command Preview:${COLOR_RESET}"
        echo "aws logs start-query \\"
        echo "    --log-group-name \"${LOG_GROUP}\" \\"
        echo "    --start-time ${START_EPOCH} \\"
        echo "    --end-time ${END_EPOCH} \\"
        echo "    --query-string \"${QUERY_STRING}\""
        exit 0
    fi

    # Ensure Excel template exists; generate if missing
    if [[ ! -f "$TEMPLATE_PATH" ]]; then
        log_info "Excel template not found at ${TEMPLATE_PATH}. Auto-generating master template..."
        mkdir -p "$(dirname "$TEMPLATE_PATH")"
        "$PYTHON_EXEC" "$(resolve_py_path "${SCRIPT_DIR}/scripts/generate_template.py")" "$(resolve_py_path "$TEMPLATE_PATH")"
        log_success "Generated template: ${TEMPLATE_PATH}"
    fi

    # Execution Mode: Mock vs Live AWS
    if [[ "$MOCK_MODE" -eq 1 ]]; then
        log_warn "Running in MOCK mode using bundled sample trace data..."
        SAMPLE_JSON="${SCRIPT_DIR}/sample_data/spans_query_result.json"
        if [[ ! -f "$SAMPLE_JSON" ]]; then
            log_error "Mock sample file not found: ${SAMPLE_JSON}"
            exit 1
        fi
        cp "$SAMPLE_JSON" "$JSON_OUT_PATH"
        log_info "Loaded mock query results into: ${JSON_OUT_PATH}"
    else
        # Prepare AWS CLI arguments
        AWS_CMD_ARGS=()
        if [[ -n "$AWS_REGION" ]]; then
            AWS_CMD_ARGS+=(--region "$AWS_REGION")
        fi
        if [[ -n "$AWS_PROFILE" ]]; then
            AWS_CMD_ARGS+=(--profile "$AWS_PROFILE")
        fi

        log_info "Starting CloudWatch Logs Insights query..."
        START_RESP="$("$AWS_EXEC" logs start-query \
            --log-group-name "$LOG_GROUP" \
            --start-time "$START_EPOCH" \
            --end-time "$END_EPOCH" \
            --query-string "$QUERY_STRING" \
            "${AWS_CMD_ARGS[@]}" \
            --output json)"

        QUERY_ID="$(echo "$START_RESP" | "$PYTHON_EXEC" -c "import sys, json; print(json.load(sys.stdin).get('queryId', ''))")"

        if [[ -z "$QUERY_ID" ]]; then
            log_error "Failed to retrieve queryId from CloudWatch Logs. Response: $START_RESP"
            exit 1
        fi

        log_info "Query started successfully. Query ID: ${COLOR_BOLD}${QUERY_ID}${COLOR_RESET}"
        log_info "Waiting for query results..."

        # Polling loop
        MAX_WAIT_SECONDS=180
        POLL_INTERVAL=2
        ELAPSED=0
        STATUS="Running"

        while [[ "$ELAPSED" -lt "$MAX_WAIT_SECONDS" ]]; do
            POLL_RESP="$("$AWS_EXEC" logs get-query-results --query-id "$QUERY_ID" "${AWS_CMD_ARGS[@]}" --output json)"
            STATUS="$(echo "$POLL_RESP" | "$PYTHON_EXEC" -c "import sys, json; print(json.load(sys.stdin).get('status', 'Unknown'))")"

            if [[ "$STATUS" == "Complete" ]]; then
                echo "$POLL_RESP" > "$JSON_OUT_PATH"
                break
            elif [[ "$STATUS" == "Failed" || "$STATUS" == "Cancelled" || "$STATUS" == "Timeout" ]]; then
                log_error "Query ended with unexpected status: ${STATUS}"
                echo "$POLL_RESP" > "$JSON_OUT_PATH"
                exit 1
            fi

            sleep "$POLL_INTERVAL"
            ELAPSED=$(( ELAPSED + POLL_INTERVAL ))
            echo -n "."
        done
        echo ""

        if [[ "$STATUS" != "Complete" ]]; then
            log_error "Query timed out after ${MAX_WAIT_SECONDS} seconds."
            exit 1
        fi
    fi

    # Step 2: Transform JSON query results into standard CSV
    log_info "Transforming query results to CSV..."
    "$PYTHON_EXEC" "$(resolve_py_path "${SCRIPT_DIR}/scripts/csv_transformer.py")" \
        "$(resolve_py_path "$JSON_OUT_PATH")" \
        "$(resolve_py_path "$CSV_OUT_PATH")"
    log_success "Exported CSV: ${CSV_OUT_PATH}"

    # Step 3: Inject CSV into Excel Template
    log_info "Injecting spans into Excel template (${TEMPLATE_PATH})..."
    "$PYTHON_EXEC" "$(resolve_py_path "${SCRIPT_DIR}/scripts/inject_to_excel.py")" \
        --csv "$(resolve_py_path "$CSV_OUT_PATH")" \
        --template "$(resolve_py_path "$TEMPLATE_PATH")" \
        --output "$(resolve_py_path "$EXCEL_OUT_PATH")" \
        ${TRACE_ID:+--trace-id "$TRACE_ID"} \
        --start-time "$START_ISO" \
        --end-time "$END_ISO" \
        --filter "${FILTER_CONDITION:-All Spans}" \
        --log-group "$LOG_GROUP"

    log_success "Generated Excel Report: ${EXCEL_OUT_PATH}"

    echo ""
    echo -e "${COLOR_BOLD}============================================================${COLOR_RESET}"
    echo -e "${COLOR_GREEN}${COLOR_BOLD} TRACE REPORT COMPLETED SUCCESSFULLY ${COLOR_RESET}"
    echo -e "${COLOR_BOLD}============================================================${COLOR_RESET}"
    echo -e "  - Raw JSON Results:  ${JSON_OUT_PATH}"
    echo -e "  - Exported Spans CSV: ${CSV_OUT_PATH}"
    echo -e "  - Excel Trace Report: ${EXCEL_OUT_PATH}"
    echo -e "============================================================"
}

main "$@"
